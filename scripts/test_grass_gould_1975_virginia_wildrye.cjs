"use strict";
// Gould (1975), The Grasses of Texas, p. 166: source-only Virginia wildrye intake and true-spike display.
// Production species shards and original scored states must remain unchanged.
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"../site/visual-key-lab");
const read=n=>JSON.parse(fs.readFileSync(path.join(root,n),"utf8"));
const reference=read("source-reference-gould-1975-elymus-virginicus.json");
const oldGould=read("source-reference-gould-1975.json");
const speciesFiles=["species-a.json","species-b.json","species-c1.json","species-c2.json","species-c3.json","species-d1.json","species-d2.json","species-d3.json","species-d4.json"];
const species=speciesFiles.flatMap(read);
assert.equal(species.length,112);
const wildrye=species.find(x=>x.id==="elymus-virginicus");
assert(wildrye);
assert.equal(reference.source.id,"gould-1975-grasses-of-texas");
assert.equal(reference.source_intake.species_id,wildrye.id);
assert.equal(reference.source_intake.taxon,wildrye.scientific);
assert.equal(reference.source_intake.printed_page,166);
assert.equal(reference.source_intake.figure_number,84);
assert.equal(oldGould.source_intake.taxon,"Schizachyrium scoparium");
assert.equal(reference.classification_decision.action,"KEEP_EXISTING_STATE");
assert.equal(reference.classification_decision.existing_state,"spike");
assert.equal(wildrye.traits.head.length,1);
assert.equal(wildrye.traits.head[0],"spike");
assert.deepEqual(wildrye.traits.awns,["long","none_obvious"]);
assert(!wildrye.traits.head.includes("foxtail"));
assert(!Object.hasOwn(wildrye,"gould_source_intake"));
assert.equal(wildrye.photos.find(x=>x.i===1)?.creator,"Matt Lavin");
const evidence=new Map(reference.observations.map(x=>[x.character,x]));
assert.equal(evidence.size,reference.observations.length);
assert.deepEqual(evidence.get("culm_height").range_cm,[60,120]);
assert.deepEqual(evidence.get("blade_width").width_mm,[5,15]);
assert.deepEqual(evidence.get("lemma_awn").length_mm,[5,25]);
assert.equal(evidence.get("chromosome_number").reported_2n,28);
assert.equal(evidence.get("inflorescence").status,"DIRECT_HEAD_ARCHITECTURE_KEEP_SPIKE");
assert.equal(evidence.get("page_continuation").status,"HOLD_NOT_VISIBLE_IN_SUBMITTED_PHOTO");
assert.equal(reference.learner_diagnostic_checks.length,3);
assert(reference.learner_diagnostic_checks.every(x=>x.source.includes("Gould")&&x.url.startsWith("https://")));
const html=fs.readFileSync(path.join(root,"index.html"),"utf8");
assert(html.includes('["spike","Long upright or nodding spike"'));
assert(html.includes('"elymus-virginicus",1]'));
assert(html.includes('["foxtail","A dense bristly cylinder"'));
assert(html.includes("sterile branchlets"));
assert(html.includes('fetch("source-reference-gould-1975-elymus-virginicus.json"'));
assert(html.includes("const virginiaGouldChecks="));
assert(html.includes("...virginiaGouldChecks"));
assert(html.includes("for(const c of displayedChecks)"));
console.log("PASS: Gould p.166 Virginia wildrye anatomy and source notes retained; true spike displayed separately from foxtail with original 112 scoring untouched");

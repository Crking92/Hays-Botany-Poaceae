#!/usr/bin/env python3
"""Synthetic isolated grass-panel upload, no real source images altered."""
import json,shutil,tempfile,subprocess,sys
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
PUB=ROOT/"scripts/publish_approved_grass_photos.py"
SID="schizachyrium-scoparium"
def execute(source,site,pass_expected=True,check=False):
    cmd=[sys.executable,str(PUB),"--source-root",str(source),"--site-root",str(site)]
    if check:cmd+=["--check"]
    p=subprocess.run(cmd,text=True,capture_output=True)
    if (p.returncode==0)!=pass_expected:raise AssertionError(p.stdout+p.stderr)
    return json.loads(p.stdout) if pass_expected else {}
def main():
    orig=json.loads((ROOT/"site/data/gallery-index.json").read_text())
    with tempfile.TemporaryDirectory(prefix="poaceae-qa-") as t:
        d=Path(t);site=d/"site";source=d/"source"
        shutil.copytree(ROOT/"site/data",site/"data")
        folder=source/"photo-intake/approved"/SID;folder.mkdir(parents=True)
        img=folder/"qa-synthetic-grass-anatomy-test.jpg"
        Image.new("RGB",(320,240),(220,220,200)).save(img,quality=90)
        meta={"species_id":SID,"photo_file":img.name,
              "status":"APPROVED_FOR_PUBLIC_FAMILY_SITE","rights_approved_for_public":True,
              "taxon_reviewed":True,"approved_by":"Isolated CI fixture, never a real photo",
              "approval_note":"CI-owned synthetic test image made by test code; no external plant claims",
              "creator":"Hays Botany isolated QA fixture",
              "source_page":"https://github.com/Crking92/Hays-Botany-Poaceae",
              "source_page_is_exact":True,"license":"CC0 1.0",
              "license_url":"https://creativecommons.org/publicdomain/zero/1.0/",
              "role":"Synthetic test placeholder, not a botanical identification",
              "modifications":"Generated by QA"}
        sidecar=img.with_name(img.name+".json");sidecar.write_text(json.dumps(meta))
        assert execute(source,site,check=True)["installed"]==1
        assert not (site/"media"/SID/img.name).exists()
        r=execute(source,site)
        assert r["installed"]==1
        record=json.loads((site/"data/species"/(SID+".json")).read_text())
        before=json.loads((ROOT/"site/data/species"/(SID+".json")).read_text())
        assert len(record["panels"])==len(before["panels"])+1
        assert record["panels"][:-1]==before["panels"]
        assert execute(source,site)["installed"]==0
        meta["rights_approved_for_public"]=False;sidecar.write_text(json.dumps(meta))
        execute(source,site,pass_expected=False,check=True)
        meta["rights_approved_for_public"]=True
        meta["species_id"]="wrong";sidecar.write_text(json.dumps(meta))
        execute(source,site,pass_expected=False,check=True)
    assert json.loads((ROOT/"site/data/gallery-index.json").read_text())==orig
    print("PASS: indexed grass photo panels, exact existing annotations, repeat and license rejection")
if __name__=="__main__":main()
